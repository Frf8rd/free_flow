const sortedSitePhrases = [...sitePhrases].sort((a, b) => b[0].length - a[0].length);

function createReplacementTable(locale: Locale) {
  const localeIndex = locale === "ro" ? 0 : locale === "en" ? 1 : 2;
  const variants = new Map<string, string>();
  for (const phrase of sortedSitePhrases) {
    for (const variant of phrase) {
      if (!variants.has(variant)) variants.set(variant, phrase[localeIndex]);
    }
  }
  const alternatives = [...variants.keys()]
    .sort((a, b) => b.length - a.length)
    .map((phrase) => phrase.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"));
  return {
    variants,
    pattern: new RegExp(
      `(^|[^\\p{L}\\p{N}])(${alternatives.join("|")})(?=$|[^\\p{L}\\p{N}])`,
      "gu",
    ),
  };
}

const replacementTables: Record<Locale, ReturnType<typeof createReplacementTable>> = {
  ro: createReplacementTable("ro"),
  en: createReplacementTable("en"),
  ru: createReplacementTable("ru"),
};

export function translatePhrase(text: string, locale: Locale): string {
  if (!text) return text;
  const { pattern, variants } = replacementTables[locale];
  return text.replace(
    pattern,
    (_match, prefix: string, phrase: string) => `${prefix}${variants.get(phrase) ?? phrase}`,
  );
}

interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

function getInitialLocale(): Locale {
  if (typeof window === "undefined") return "ro";
  try {
    const saved = localStorage.getItem(LOCALE_STORAGE_KEY);
    if (saved === "ro" || saved === "ru" || saved === "en") return saved;
  } catch (error) {
    console.warn("Could not read the saved language preference.", error);
  }
  return "ro";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(getInitialLocale);
  const translationState = useState(() => ({
    textNodes: new WeakMap<Text, { source: string; rendered: string }>(),
    attributes: new WeakMap<Element, Map<string, { source: string; rendered: string }>>(),
  }))[0];

  useEffect(() => {
    document.documentElement.lang = locale;
    const attributesToTranslate = [
      "aria-label",
      "aria-description",
      "title",
      "placeholder",
      "alt",
      "content",
    ];

    const translateTextNode = (node: Text) => {
      const current = node.nodeValue ?? "";
      const previous = translationState.textNodes.get(node);
      const source = previous && previous.rendered === current ? previous.source : current;
      const rendered = translatePhrase(source, locale);
      translationState.textNodes.set(node, { source, rendered });
      if (rendered !== current) node.nodeValue = rendered;
    };

    const translateElement = (element: Element) => {
      if (element.matches("script, style, noscript, [data-no-translate]")) return;
      const attributes = translationState.attributes.get(element) ?? new Map();
      for (const name of attributesToTranslate) {
        const current = element.getAttribute(name);
        if (current === null) continue;
        const previous = attributes.get(name);
        const source = previous && previous.rendered === current ? previous.source : current;
        const rendered = translatePhrase(source, locale);
        attributes.set(name, { source, rendered });
        if (rendered !== current) element.setAttribute(name, rendered);
      }
      translationState.attributes.set(element, attributes);
    };

    const translateTree = (node: Node) => {
      if (node.nodeType === Node.TEXT_NODE) {
        const parent = node.parentElement;
        if (parent && !parent.closest("script, style, noscript, [data-no-translate]")) {
          translateTextNode(node as Text);
        }
        return;
      }
      if (node.nodeType !== Node.ELEMENT_NODE && node.nodeType !== Node.DOCUMENT_NODE) return;
      if (node instanceof Element) translateElement(node);
      const walker = document.createTreeWalker(
        node,
        NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT,
      );
      let child: Node | null;
      while ((child = walker.nextNode())) {
        if (child instanceof Element) {
          translateElement(child);
        } else if (child.nodeType === Node.TEXT_NODE) {
          const parent = child.parentElement;
          if (parent && !parent.closest("script, style, noscript, [data-no-translate]")) {
            translateTextNode(child as Text);
          }
        }
      }
    };

    translateTree(document.documentElement);
    const observer = new MutationObserver((records) => {
      for (const record of records) {
        if (record.type === "characterData" && record.target.nodeType === Node.TEXT_NODE) {
          translateTextNode(record.target as Text);
        } else if (record.type === "attributes" && record.target instanceof Element) {
          translateElement(record.target);
        } else {
          record.addedNodes.forEach(translateTree);
        }
      }
    });
    observer.observe(document.documentElement, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: attributesToTranslate,
    });
    return () => observer.disconnect();
  }, [locale, translationState]);

  const setLocale = (nextLocale: Locale) => {
    setLocaleState(nextLocale);
    try {
      localStorage.setItem(LOCALE_STORAGE_KEY, nextLocale);
    } catch (error) {
      console.warn("Could not save the selected language preference.", error);
    }
  };

  const t = (key: string) => translations[locale][key] ?? translations.ro[key] ?? key;

  return <I18nContext.Provider value={{ locale, setLocale, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside I18nProvider");
  return context;
}
